// Emitters for limits.yaml: TypeScript, Go, Rust, Kotlin and Swift. Every emitter is a pure
// function of the parsed limits, so `check` can regenerate into a temp dir and diff.
import { camel, padTo, pascal, pascalGo, screaming } from "../naming.mjs";

const SOURCE = "packages/contracts/limits.yaml";
const REGEN = "Regenerate with `make -C packages/contracts gen`.";

// English doc comments per group. Unknown groups get a generic line.
const GROUP_DOCS = Object.freeze({
  text: "Text limits, in characters (Unicode code points after NFC normalization). A limit of 0 disables the feature.",
  files: "File, upload and archive limits. Plan limits in config/pricing.yaml are always at or below these.",
  http: "HTTP server limits and timeouts.",
  ids: "Identifier lengths and cardinality limits.",
});

function groupDoc(name) {
  return GROUP_DOCS[name] ?? `Limits in the \`${name}\` group of limits.yaml.`;
}

function dotted(limits) {
  const out = [];
  for (const g of limits.groups) for (const e of g.entries) out.push({ key: `${g.name}.${e.key}`, group: g, entry: e });
  return out;
}

// ------------------------------------------------------------------------------ TypeScript

export function emitLimitsTs(limits) {
  const lines = [];
  lines.push(`// Code generated by tools/codegen from ${SOURCE}. DO NOT EDIT.`);
  lines.push(`// ${REGEN}`);
  lines.push("");
  lines.push("/**");
  lines.push(` * Shared input limits (limits.yaml, version ${limits.version}). The client applies \`maxlength\``);
  lines.push(" * with a counter from 80%; the server re-applies the same numbers after NFC normalization.");
  lines.push(" */");
  lines.push("export const LIMITS = {");
  lines.push(`  version: ${limits.version},`);
  for (const g of limits.groups) {
    lines.push(`  /** ${groupDoc(g.name)} */`);
    lines.push(`  ${g.name}: {`);
    for (const e of g.entries) lines.push(`    ${e.key}: ${e.value},`);
    lines.push("  },");
  }
  lines.push("} as const;");
  lines.push("");
  lines.push("export type Limits = typeof LIMITS;");
  lines.push("");
  lines.push("/** Limit group names. */");
  lines.push("export type LimitGroup = Exclude<keyof Limits, 'version'>;");
  lines.push("");
  lines.push("/** Dotted limit key, as used by `x-limit` in the OpenAPI contract (ex.: `text.display_name`). */");
  lines.push("export type LimitKey =");
  const keys = dotted(limits);
  keys.forEach(({ key }, i) => lines.push(`  | '${key}'${i === keys.length - 1 ? ";" : ""}`));
  lines.push("");
  lines.push("/** Every limit by dotted key. */");
  lines.push("export const LIMIT_BY_KEY: Readonly<Record<LimitKey, number>> = {");
  for (const { key, entry } of keys) lines.push(`  '${key}': ${entry.value},`);
  lines.push("};");
  lines.push("");
  lines.push("/** Returns the value of a dotted limit key. */");
  lines.push("export function limit(key: LimitKey): number {");
  lines.push("  return LIMIT_BY_KEY[key];");
  lines.push("}");
  lines.push("");
  lines.push("/** True when `key` names a limit (useful for data coming from `x-limit`). */");
  lines.push("export function isLimitKey(key: string): key is LimitKey {");
  lines.push("  return Object.hasOwn(LIMIT_BY_KEY, key);");
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

// ------------------------------------------------------------------------------ Go

export function goLimitName(group, key) {
  return `${pascalGo(group)}${pascalGo(key)}`;
}

export function emitLimitsGo(limits) {
  const lines = [];
  lines.push(`// Code generated by tools/codegen from ${SOURCE}. DO NOT EDIT.`);
  lines.push("");
  lines.push("// Package contracts holds the constants generated from packages/contracts: input limits");
  lines.push("// (limits.go) and the error catalog (errors.go). Nothing here is typed by hand; regenerate");
  lines.push("// with `make -C packages/contracts gen`.");
  lines.push("package contracts");
  lines.push("");
  lines.push("// LimitsVersion is the `version` field of limits.yaml.");
  lines.push(`const LimitsVersion = ${limits.version}`);
  for (const g of limits.groups) {
    lines.push("");
    lines.push(`// ${groupDoc(g.name)}`);
    lines.push("const (");
    const names = g.entries.map((e) => goLimitName(g.name, e.key));
    const width = Math.max(...names.map((n) => n.length));
    g.entries.forEach((e, i) => lines.push(`\t${padTo(names[i], width)} = ${e.value}`));
    lines.push(")");
  }
  lines.push("");
  lines.push("// LimitByKey resolves a dotted limit key as used by `x-limit` in the OpenAPI contract");
  lines.push('// (ex.: "text.display_name"). The second value is false for unknown keys.');
  lines.push("func LimitByKey(key string) (int, bool) {");
  lines.push("\tv, ok := limitByKey[key]");
  lines.push("\treturn v, ok");
  lines.push("}");
  lines.push("");
  lines.push("var limitByKey = map[string]int{");
  const keys = dotted(limits);
  // gofmt aligns the values one space after the longest `"key":`.
  const width = Math.max(...keys.map(({ key }) => key.length + 3)) + 1;
  for (const { key, group, entry } of keys) {
    lines.push(`\t${padTo(`"${key}":`, width)}${goLimitName(group.name, entry.key)},`);
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

// ------------------------------------------------------------------------------ Rust

export function emitLimitsRs(limits) {
  const lines = [];
  lines.push(`//! Code generated by tools/codegen from ${SOURCE}. DO NOT EDIT.`);
  lines.push("//!");
  lines.push(`//! Shared input limits (limits.yaml, version ${limits.version}). Text limits count Unicode`);
  lines.push("//! scalar values after NFC normalization. Use from a crate with");
  lines.push('//! `#[path = "../../packages/contracts/gen/limits.rs"] mod limits;` (adjust the path).');
  lines.push("");
  lines.push("/// The `version` field of limits.yaml.");
  lines.push(`pub const LIMITS_VERSION: u32 = ${limits.version};`);
  for (const g of limits.groups) {
    lines.push("");
    lines.push(`/// ${groupDoc(g.name)}`);
    lines.push(`pub mod ${g.name} {`);
    g.entries.forEach((e, i) => {
      if (i > 0) lines.push("");
      lines.push(`    /// \`${g.name}.${e.key}\``);
      lines.push(`    pub const ${screaming(e.key)}: u32 = ${e.value};`);
    });
    lines.push("}");
  }
  lines.push("");
  lines.push("/// Resolves a dotted limit key as used by `x-limit` in the OpenAPI contract");
  lines.push("/// (ex.: `text.display_name`). Returns `None` for unknown keys.");
  lines.push("pub fn limit_by_key(key: &str) -> Option<u32> {");
  lines.push("    match key {");
  for (const { key, group, entry } of dotted(limits)) {
    lines.push(`        "${key}" => Some(${group.name}::${screaming(entry.key)}),`);
  }
  lines.push("        _ => None,");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  lines.push("/// Every dotted key, in limits.yaml order.");
  lines.push("pub const LIMIT_KEYS: &[&str] = &[");
  for (const { key } of dotted(limits)) lines.push(`    "${key}",`);
  lines.push("];");
  return `${lines.join("\n")}\n`;
}

// ------------------------------------------------------------------------------ Kotlin

export function emitLimitsKt(limits, pkg = "br.com.docmatch.contracts") {
  const lines = [];
  lines.push(`// Code generated by tools/codegen from ${SOURCE}. DO NOT EDIT.`);
  lines.push(`// ${REGEN}`);
  lines.push("");
  lines.push(`package ${pkg}`);
  lines.push("");
  lines.push("/**");
  lines.push(` * Shared input limits (limits.yaml, version ${limits.version}). Text limits count Unicode code`);
  lines.push(" * points after NFC normalization (use `codePointCount`, not `length`).");
  lines.push(" */");
  lines.push("object Limits {");
  lines.push(`    const val VERSION: Int = ${limits.version}`);
  for (const g of limits.groups) {
    lines.push("");
    lines.push(`    /** ${groupDoc(g.name)} */`);
    lines.push(`    object ${pascal(g.name)} {`);
    for (const e of g.entries) lines.push(`        const val ${screaming(e.key)}: Int = ${e.value}`);
    lines.push("    }");
  }
  lines.push("");
  lines.push("    /** Resolves a dotted limit key (`text.display_name`); null when unknown. */");
  lines.push("    fun byKey(key: String): Int? = BY_KEY[key]");
  lines.push("");
  lines.push("    private val BY_KEY: Map<String, Int> = mapOf(");
  for (const { key, group, entry } of dotted(limits)) {
    lines.push(`        "${key}" to ${pascal(group.name)}.${screaming(entry.key)},`);
  }
  lines.push("    )");
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

// ------------------------------------------------------------------------------ Swift

export function emitLimitsSwift(limits) {
  const lines = [];
  lines.push(`// Code generated by tools/codegen from ${SOURCE}. DO NOT EDIT.`);
  lines.push(`// ${REGEN}`);
  lines.push("");
  lines.push(`/// Shared input limits (limits.yaml, version ${limits.version}). Text limits count Unicode scalar`);
  lines.push("/// values after NFC normalization (`unicodeScalars.count` on a precomposed string).");
  lines.push("public enum Limits {");
  lines.push(`    public static let version: Int = ${limits.version}`);
  for (const g of limits.groups) {
    lines.push("");
    lines.push(`    /// ${groupDoc(g.name)}`);
    lines.push(`    public enum ${pascalGo(g.name)} {`);
    for (const e of g.entries) lines.push(`        public static let ${camel(e.key)}: Int = ${e.value}`);
    lines.push("    }");
  }
  lines.push("");
  lines.push("    /// Resolves a dotted limit key (`text.display_name`); nil when unknown.");
  lines.push("    public static func byKey(_ key: String) -> Int? {");
  lines.push("        byKeyTable[key]");
  lines.push("    }");
  lines.push("");
  lines.push("    private static let byKeyTable: [String: Int] = [");
  for (const { key, group, entry } of dotted(limits)) {
    lines.push(`        "${key}": ${pascalGo(group.name)}.${camel(entry.key)},`);
  }
  lines.push("    ]");
  lines.push("}");
  return `${lines.join("\n")}\n`;
}
