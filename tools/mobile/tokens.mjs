#!/usr/bin/env node
// Colors, radii and spacing of packages/design-tokens/tokens.json for the apps, so Android and iOS
// use exactly the site's palette (light and dark) and AA-checked pairs.
//
//   node tools/mobile/tokens.mjs           writes the Kotlin and Swift files
//   node tools/mobile/tokens.mjs --check   fails when a committed file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const tokens = JSON.parse(readFileSync(join(root, 'packages/design-tokens/tokens.json'), 'utf8'));

const outputs = {
  kotlin: join(root, 'apps/android/app/src/main/kotlin/br/com/docmatch/app/ui/Tokens.kt'),
  swift: join(root, 'apps/ios/Docmatch/Theme/Tokens.swift'),
  web: join(root, 'apps/web/src/styles/palette.generated.css'),
};

const HEADER = 'Code generated by tools/mobile/tokens.mjs from packages/design-tokens/tokens.json. DO NOT EDIT.';

function flatten(node, prefix = [], out = []) {
  for (const [k, v] of Object.entries(node)) {
    if (v && typeof v === 'object') flatten(v, [...prefix, k], out);
    else out.push({ path: [...prefix, k], value: v });
  }
  return out;
}

const camel = (parts) =>
  parts
    .join('_')
    .split('_')
    .filter(Boolean)
    .map((w, i) => (i === 0 ? w.toLowerCase() : w[0].toUpperCase() + w.slice(1).toLowerCase()))
    .join('');

function hexOf(value) {
  const m = /^#([0-9A-Fa-f]{6})$/.exec(String(value));
  if (!m) throw new Error(`cor inválida: ${value}`);
  return m[1].toUpperCase();
}

function colorNames() {
  const light = flatten(tokens.color.light);
  const dark = new Map(flatten(tokens.color.dark).map((c) => [c.path.join('.'), c.value]));
  return light.map((c) => {
    const key = c.path.join('.');
    if (!dark.has(key)) throw new Error(`cor sem par escuro: ${key}`);
    return { name: camel(c.path), light: hexOf(c.value), dark: hexOf(dark.get(key)) };
  });
}

function kotlin() {
  const colors = colorNames();
  const field = (c, scheme) => `        val ${c.name} = Color(0xFF${scheme === 'light' ? c.light : c.dark})`;
  const radius = Object.entries(tokens.radius).map(([k, v]) => `    val ${camel(['radius', k])} = ${v}.dp`);
  const space = Object.entries(tokens.space).map(([k, v]) => `    val ${camel(['space', k])} = ${v}.dp`);
  return `// ${HEADER}
// Regenerate with \`node tools/mobile/tokens.mjs\`.
package br.com.docmatch.app.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/** The palette of the site (tokens.json), light and dark. */
object DmColors {
    object Light {
${colors.map((c) => field(c, 'light')).join('\n')}
    }

    object Dark {
${colors.map((c) => field(c, 'dark')).join('\n')}
    }
}

/** Radii and the 8-point spacing scale of tokens.json. */
object DmSize {
${[...radius, ...space].join('\n')}
}
`;
}

function swift() {
  const colors = colorNames();
  const rgb = (hex) => {
    const n = parseInt(hex, 16);
    const c = (v) => Number((v / 255).toFixed(4));
    return `red: ${c((n >> 16) & 255)}, green: ${c((n >> 8) & 255)}, blue: ${c(n & 255)}`;
  };
  const props = colors.map(
    (c) => `    /// ${c.light} / ${c.dark}\n    public static let ${c.name} = DmColor(light: .init(${rgb(c.light)}), dark: .init(${rgb(c.dark)}))`,
  );
  const radius = Object.entries(tokens.radius).map(([k, v]) => `    public static let ${camel(['radius', k])}: Double = ${v}`);
  const space = Object.entries(tokens.space).map(([k, v]) => `    public static let ${camel(['space', k])}: Double = ${v}`);
  return `// ${HEADER}
// Regenerate with \`node tools/mobile/tokens.mjs\`.

/// One color of the palette in both schemes (components 0...1, sRGB).
public struct DmColor: Sendable {
    public struct RGB: Sendable {
        public let red: Double
        public let green: Double
        public let blue: Double
    }

    public let light: RGB
    public let dark: RGB
}

/// The palette of the site (tokens.json), light and dark.
public enum DmColors {
${props.join('\n')}
}

/// Radii and the 8-point spacing scale of tokens.json, in points.
public enum DmSize {
${[...radius, ...space].join('\n')}
}
`;
}

// The public site and native apps share these colors; workspace appearance overrides use
// the same values, so a client choosing light/dark cannot reintroduce a stale palette.
const webNames = {
  bg: 'bg.canvas', fg: 'text.primary', muted: 'text.muted', surface: 'bg.surface',
  'surface-2': 'bg.subtle', border: 'border.default', 'border-strong': 'border.strong',
  accent: 'brand.primary', 'accent-hover': 'brand.primary_hover', 'accent-fg': 'brand.on_primary',
  'accent-soft': 'brand.subtle', danger: 'status.danger', 'danger-soft': 'status.danger_soft',
  success: 'status.success', 'success-soft': 'status.success_soft', warning: 'status.warning',
  'warning-soft': 'status.warning_soft', info: 'status.info', 'info-soft': 'status.info_soft',
  focus: 'border.focus',
};
function webPalette() {
  const declarations = (mode, indent = '  ') => Object.entries(webNames).map(([name, path]) => {
    const [group, key] = path.split('.');
    return `${indent}--color-${name}: ${tokens.color[mode][group][key].toLowerCase()};`;
  }).join('\n');
  return `/* ${HEADER} */\n:root {\n${declarations('light')}\n}\n\n@media (prefers-color-scheme: dark) {\n  :root {\n${declarations('dark', '    ')}\n  }\n}\n\n.workspace-shell[data-workspace-mode='light'] {\n${declarations('light')}\n}\n\n.workspace-shell[data-workspace-mode='dark'] {\n${declarations('dark')}\n}\n`;
}

const files = { [outputs.kotlin]: kotlin(), [outputs.swift]: swift(), [outputs.web]: webPalette() };
const check = process.argv.includes('--check');
let stale = 0;
for (const [path, content] of Object.entries(files)) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== content) {
      console.error(`tokens: ${relative(root, path)} está desatualizado (rode node tools/mobile/tokens.mjs)`);
      stale++;
    }
  } else if (current !== content) {
    writeFileSync(path, content);
    console.log(`tokens: escrito ${relative(root, path)}`);
  }
}
process.exit(stale ? 1 : 0);
