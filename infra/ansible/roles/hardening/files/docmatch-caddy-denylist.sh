#!/usr/bin/env bash
# Regenerates /etc/caddy/snippets/denylist.caddy from the fail2ban list of banned client
# addresses and reloads Caddy. Addresses are the viewer addresses forwarded by CloudFront, so the
# ban happens at the HTTP layer where it is effective.
set -euo pipefail
list="/var/lib/fail2ban/caddy-denylist.txt"
snippet="/etc/caddy/snippets/denylist.caddy"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
ips=()
if [[ -r "$list" ]]; then
  while IFS= read -r ip; do
    [[ "$ip" =~ ^[0-9a-fA-F.:/]+$ ]] && ips+=("$ip")
  done < "$list"
fi
{
  echo "# Generated by docmatch-caddy-denylist at $(date -u +%FT%TZ); ${#ips[@]} banned addresses"
  if [[ ${#ips[@]} -gt 0 ]]; then
    printf '@denied client_ip %s\n' "${ips[*]}"
    echo 'respond @denied 404'
  fi
} > "$tmp"
install -m 0640 -o root -g caddy "$tmp" "$snippet"
if systemctl is-active --quiet caddy; then
  systemctl reload caddy
fi
