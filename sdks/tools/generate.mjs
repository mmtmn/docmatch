// Apache-2.0. Reproducible operation catalogs from the public contract.
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import YAML from '../../tools/codegen/node_modules/yaml/dist/index.js';
function emit(url, content) {
  if (url.pathname.endsWith('.go'))
    content = execFileSync('gofmt', [], { input: content, encoding: 'utf8' });
  if (url.pathname.endsWith('.rs'))
    content = execFileSync('rustfmt', ['--emit', 'stdout'], { input: content, encoding: 'utf8' });
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8') !== content)
      throw new Error('Generated SDK catalog is stale: ' + url.pathname);
  } else writeFileSync(url, content);
}
const root = new URL('../', import.meta.url),
  raw = readFileSync(new URL('../../packages/contracts/openapi.yaml', import.meta.url), 'utf8');
const spec = YAML.parse(raw),
  hash = createHash('sha256').update(raw).digest('hex');
const wanted = [
  'createUpload',
  'completeUpload',
  'estimateRun',
  'createRun',
  'getRun',
  'listFindings',
  'exportRun',
];
const operations = {};
for (const [path, item] of Object.entries(spec.paths))
  for (const [method, op] of Object.entries(item))
    if (op.operationId && wanted.includes(op.operationId))
      operations[op.operationId] = { method: method.toUpperCase(), path: '/v1' + path };
emit(
  new URL('operations.json', root),
  JSON.stringify({ schema_sha256: hash, operations }, null, 2) + '\n',
);
emit(
  new URL('typescript/src/operations.ts', root),
  '// Generated by sdks/tools/generate.mjs. Apache-2.0.\nexport const operations = ' +
    JSON.stringify(operations, null, 2) +
    ' as const;\n',
);
emit(
  new URL('python/docmatch/operations.py', root),
  '# Generated by sdks/tools/generate.mjs. Apache-2.0.\nOPERATIONS = ' +
    JSON.stringify(operations, null, 2) +
    '\n',
);
emit(
  new URL('go/operations.go', root),
  '// Code generated by sdks/tools/generate.mjs; DO NOT EDIT. Apache-2.0.\npackage docmatch\n\nvar Operations = map[string]struct{Method,Path string}{\n' +
    Object.entries(operations)
      .map(
        ([k, v]) =>
          JSON.stringify(k) + ':{' + JSON.stringify(v.method) + ',' + JSON.stringify(v.path) + '},',
      )
      .join('\n') +
    '\n}\n',
);
emit(
  new URL('rust/src/operations.rs', root),
  '// Generated by sdks/tools/generate.mjs. Apache-2.0.\npub const OPERATIONS: &[(&str,&str,&str)] = &[\n' +
    Object.entries(operations)
      .map(([k, v]) => '(' + [k, v.method, v.path].map(JSON.stringify).join(',') + '),')
      .join('\n') +
    '\n];\n',
);
if (Object.keys(operations).length !== wanted.length)
  throw new Error('Missing SDK operation in OpenAPI');
console.log(
  process.argv.includes('--check') ? 'Checked' : 'Generated',
  Object.keys(operations).length,
  'SDK operations',
);
